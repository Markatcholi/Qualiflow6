const {PGlite}=require(process.env.PGLITE_MODULE);
const {readFileSync}=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
 const db=new PGlite();
 const tenant='00000000-0000-0000-0000-000000000001',other='00000000-0000-0000-0000-000000000002';
 await db.exec(`CREATE ROLE anon;CREATE ROLE authenticated;CREATE SCHEMA auth;
 CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$SELECT '00000000-0000-0000-0000-000000000001'::uuid$$;
 CREATE FUNCTION qualisphere_training_is_coordinator(uuid) RETURNS boolean LANGUAGE sql AS $$SELECT current_setting('test.coordinator')='true' AND $1=current_setting('test.tenant')::uuid$$;
 CREATE TABLE training_methods(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),tenant_id uuid,code text,label text,release_blocking boolean,acknowledgement_required boolean,evidence_required boolean,is_active boolean DEFAULT true,updated_at timestamptz DEFAULT now(),UNIQUE(tenant_id,code));
 CREATE TABLE training_assignments(training_method_id uuid REFERENCES training_methods(id) ON DELETE SET NULL);
 CREATE TABLE document_training_requirements(training_method_id uuid REFERENCES training_methods(id));
 ALTER TABLE training_methods ENABLE ROW LEVEL SECURITY;
 CREATE POLICY member_access ON training_methods FOR ALL TO authenticated USING(tenant_id=current_setting('test.tenant')::uuid) WITH CHECK(tenant_id=current_setting('test.tenant')::uuid);
 GRANT USAGE ON SCHEMA public,auth TO authenticated;GRANT ALL ON training_methods,training_assignments,document_training_requirements TO authenticated;
 `);
 await db.query("SELECT set_config('test.coordinator','true',false),set_config('test.tenant',$1,false)",[tenant]);
 await db.exec(readFileSync('sql/training_method_management.sql','utf8'));
 await db.exec('SET ROLE authenticated');
 const save=async(id,label,ack=true,evidence=false,block=false,t=tenant)=>(await db.query('SELECT qualisphere_save_training_method($1,$2,$3,$4,$5,$6) AS value',[t,id,label,block,ack,evidence])).rows[0].value;
 const first=await save(null,'Read and Acknowledge');
 assert.equal(first.versioned,false);
 await assert.rejects(save(null,' READ AND ACKNOWLEDGE '),/already uses this name/);
 const renamed=await save(first.id,'Read and Acknowledge — GDP');assert.equal(renamed.id,first.id);
 await db.query('INSERT INTO training_assignments VALUES($1)',[first.id]);
 await assert.rejects(db.query('DELETE FROM training_methods WHERE id=$1',[first.id]),/linked to training records/);
 await assert.rejects(db.query('UPDATE training_methods SET evidence_required=true WHERE id=$1',[first.id]),/linked to training records/);
 const replacement=await save(first.id,'Read and Acknowledge — GDP',true,true);
 assert.equal(replacement.versioned,true);assert.notEqual(replacement.id,first.id);
 const original=(await db.query('SELECT * FROM training_methods WHERE id=$1',[first.id])).rows[0];
 assert.equal(original.is_active,false);assert.equal(original.evidence_required,false);
 assert.equal((await db.query('SELECT training_method_id FROM training_assignments')).rows[0].training_method_id,first.id);
 const unused=await save(null,'Classroom',false,true);
 await db.query('UPDATE training_methods SET is_active=false WHERE id=$1',[unused.id]);
 await db.query('UPDATE training_methods SET is_active=true WHERE id=$1',[unused.id]);
 await db.query('DELETE FROM training_methods WHERE id=$1',[unused.id]);
 await assert.rejects(save(null,'No completion requirement',false,false),/Choose acknowledgement/);
 await assert.rejects(save(null,'Other tenant',true,false,false,other),/coordinator permission/);
 await db.query("SELECT set_config('test.coordinator','false',false)");
 await assert.rejects(save(null,'Unauthorized'),/coordinator permission/);
 const before=(await db.query('SELECT * FROM training_methods')).rows.length;
 await db.query("UPDATE training_methods SET label='Unauthorized' WHERE id=$1",[replacement.id]);
 assert.equal((await db.query('SELECT label FROM training_methods WHERE id=$1',[replacement.id])).rows[0].label,'Read and Acknowledge — GDP');
 await assert.rejects(db.query("INSERT INTO training_methods(tenant_id,code,label) VALUES($1,'BAD','Unauthorized')",[tenant]),/row-level security/);
 assert.equal((await db.query('SELECT * FROM training_methods')).rows.length,before,'non-coordinator can still read methods');
 console.log('Training method SQL checks passed: add, edit, duplicate protection, versioned requirement changes, linked-record preservation, unused deletion, active status, coordinator permissions, tenant isolation and read access.');
 await db.close();
})().catch(e=>{console.error(e);process.exit(1)});
