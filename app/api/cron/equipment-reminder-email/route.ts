import { NextRequest, NextResponse } from "next/server";
import { createClient } from "@supabase/supabase-js";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

/**
 * Called by Vercel Cron after the Supabase Equipment workspace scheduler.
 * Uses the existing Resend account via server-only environment variables.
 * No browser-accessible keys or client-side email requests.
 */
export async function GET(request: NextRequest) {
  const cronSecret = process.env.CRON_SECRET;
  if (!cronSecret || request.headers.get("authorization") !== `Bearer ${cronSecret}`) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  const url = process.env.NEXT_PUBLIC_SUPABASE_URL || process.env.SUPABASE_URL;
  const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
  const resendKey = process.env.RESEND_API_KEY;
  const from = process.env.RESEND_FROM_EMAIL;
  const siteUrl = process.env.NEXT_PUBLIC_SITE_URL || process.env.SITE_URL;
  if (!url || !serviceKey || !resendKey || !from || !siteUrl) {
    return NextResponse.json({ error: "Equipment email configuration incomplete" }, { status: 503 });
  }

  const supabase = createClient(url, serviceKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  });

  // Restrict the email job to Equipment reminders generated by our database scheduler.
  const { data, error } = await supabase
    .from("notifications")
    .select("id,user_email,title,message,related_url")
    .eq("related_module", "equipment")
    .eq("notification_type", "equipment_schedule_reminder")
    .eq("created_by", "equipment_scheduler")
    .or("delivery_status.is.null,delivery_status.eq.pending")
    .order("created_at", { ascending: true })
    .limit(50);

  if (error) return NextResponse.json({ error: "Unable to read Equipment email queue" }, { status: 500 });

  let sent = 0;
  let failed = 0;
  for (const item of data || []) {
    if (!item.user_email || !item.id) continue;

    // Claim before sending to prevent concurrent cron executions sending twice.
    const { data: claimed, error: claimError } = await supabase
      .from("notifications")
      .update({ delivery_status: "processing" })
      .eq("id", item.id)
      .or("delivery_status.is.null,delivery_status.eq.pending")
      .select("id")
      .maybeSingle();
    if (claimError || !claimed) continue;

    try {
      const target = new URL(item.related_url || "/equipment", siteUrl).toString();
      const response = await fetch("https://api.resend.com/emails", {
        method: "POST",
        headers: {
          Authorization: `Bearer ${resendKey}`,
          "Content-Type": "application/json",
          "Idempotency-Key": `equipment-${item.id}`,
        },
        body: JSON.stringify({
          from,
          to: [item.user_email],
          subject: item.title || "QualiSphere Equipment reminder",
          text: `${item.message || "Equipment reminder"}\n\nView equipment: ${target}\n\nThis is an informational reminder, not an approval task.`,
        }),
      });
      if (!response.ok) throw new Error(`Resend returned ${response.status}`);
      await supabase.from("notifications").update({ delivery_status: "sent" }).eq("id", item.id);
      sent++;
    } catch {
      // A failed send is retained for investigation; do not automatically duplicate delivery.
      await supabase.from("notifications").update({ delivery_status: "failed" }).eq("id", item.id);
      failed++;
    }
  }
  return NextResponse.json({ processed: (data || []).length, sent, failed });
}
